#!/usr/bin/env node
/**
 * Export compass data from the study prototype (axes-render.html) into typed TS modules.
 * Run: node scripts/export-compass-data.mjs
 *
 * Source of truth: study/compass-update/axes-render.html (prototype data arrays).
 * Output: resources/js/Pages/Compass/data/{axes,questions,figures,align,spectra}.ts
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, 'study/compass-update/axes-render.html');
const OUT = path.join(ROOT, 'resources/js/Pages/Compass/data');

const html = fs.readFileSync(SRC, 'utf8');
const grab = (re, label) => {
  const m = html.match(re);
  if (!m) throw new Error(`Could not extract ${label}`);
  return m[1];
};

// eslint-disable-next-line no-eval
const AXES = eval(`[${grab(/const AXES = \[([\s\S]*?)\n\];/, 'AXES')}]`);
// eslint-disable-next-line no-eval
const FIGURES = eval(`[${grab(/const F = \[([\s\S]*?)\n\];/, 'F')}]`);
// eslint-disable-next-line no-eval
const QUESTIONS = eval(`(${grab(/const QUESTIONS = (\{[\s\S]*?\n\});/, 'QUESTIONS')})`);
// eslint-disable-next-line no-eval
const ALIGN = eval(`[${grab(/const ALIGN_Q = \[([\s\S]*?)\n\];/, 'ALIGN_Q')}]`);

const AXIS_IDS = AXES.map((a) => a.id);
const q = (s) => JSON.stringify(s);

fs.mkdirSync(OUT, { recursive: true });

// ---- axes.ts ----
const axesTs =
  `// AUTO-GENERATED by scripts/export-compass-data.mjs — do not edit by hand.\n` +
  `import type { Axis } from './types';\n\n` +
  `export const AXES: Axis[] = [\n` +
  AXES.map(
    (a) =>
      `  { id: ${q(a.id)}, name: ${q(a.name)}, left: ${q(a.l)}, right: ${q(a.r)}, desc: ${q(a.desc)} },`
  ).join('\n') +
  `\n];\n`;
fs.writeFileSync(path.join(OUT, 'axes.ts'), axesTs);

// ---- figures.ts ----
// Local portrait slugs (public/images/compass/figures/<slug>.webp). A figure is
// wired to an image only if the .webp actually exists on disk, so you can drop a
// new file in and re-run without editing this map. Figures without an image fall
// back to the symbolic category avatar.
const IMAGE_DIR = path.join(ROOT, 'public/images/compass/figures');
const IMAGES = {
  'فارس الخوري': 'fares-al-khoury', 'هاشم الأتاسي': 'hashim-al-atassi', 'شكري القوتلي': 'shukri-al-quwatli',
  'عبد الرحمن الشهبندر': 'shahbandar', 'خالد العظم': 'khalid-al-azm', 'حسني الزعيم': 'husni-al-zaim',
  'أديب الشيشكلي': 'adib-al-shishakli', 'ميشيل عفلق': 'michel-aflaq', 'أكرم الحوراني': 'akram-al-hawrani',
  'زكي الأرسوزي': 'zaki-al-arsuzi', 'أنطون سعادة': 'antoun-saadeh', 'مصطفى السباعي': 'mustafa-al-sibai',
  'مروان حديد': 'marwan-hadid', 'سعيد حوى': 'said-hawwa', 'رياض الترك': 'riad-al-turk',
  'ميشيل كيلو': 'michel-kilo', 'ياسين الحاج صالح': 'yassin-al-haj-saleh', 'مازن درويش': 'mazen-darwish',
  'مريم جلبي': 'mariam-jalabi', 'هيثم المالح': 'haitham-al-maleh', 'نور الدين زازا': 'nureddin-zaza',
  'سلطان الأطرش': 'sultan-al-atrash', 'صالح العلي': 'saleh-al-ali', 'عز الدين القسام': 'izz-al-din-al-qassam',
  'مظلوم عبدي': 'mazloum-abdi', 'حكمت الهجري': 'hikmat-al-hijri', 'غزال غزال': 'ghazal-ghazal',
  'هند قبوات': 'hind-kabawat', 'أسامة الرفاعي': 'osama-al-rifai',
  'أحمد الشرع': 'ahmed-al-sharaa', 'أسعد الشيباني': 'asaad-al-shaibani',
  // drop-in slugs for figures still lacking a portrait (provide the file to enable):
  'عصام العطار': 'issam-al-attar', 'عدنان سعد الدين': 'adnan-saad-al-din', 'كمال اللبواني': 'kamal-al-labwani',
  'فريد غادري': 'farid-ghadry', 'مشعل تمو': 'mashal-tammo', 'محمد إسماعيل': 'muhammad-ismail',
  'ليث البلعوس': 'laith-al-balou', 'إبراهيم الهفل': 'ibrahim-al-hafel', 'عائشة الدبس': 'aisha-al-dibs',
  'عبد الحميد العواك': 'abdul-hamid-al-awak',
};
const hasImage = (slug) => fs.existsSync(path.join(IMAGE_DIR, `${slug}.webp`));
const figTs =
  `// AUTO-GENERATED by scripts/export-compass-data.mjs — do not edit by hand.\n` +
  `import type { Figure, Category } from './types';\n\n` +
  `export const FIGURES: Figure[] = [\n` +
  FIGURES.map((f) => {
    const v = AXIS_IDS.map((id) => `${id}: ${f.v[id] === null ? 'null' : f.v[id]}`).join(', ');
    const slug = IMAGES[f.n];
    const img = slug && hasImage(slug) ? ` image: '/images/compass/figures/${slug}.webp',` : '';
    return `  { name: ${q(f.n)}, category: ${q(f.c)} as Category, align: ${q(f.a)},${img} positions: { ${v} } },`;
  }).join('\n') +
  `\n];\n`;
fs.writeFileSync(path.join(OUT, 'figures.ts'), figTs);
const withImg = FIGURES.filter((f) => IMAGES[f.n] && hasImage(IMAGES[f.n])).length;
console.log(`  figures with portrait: ${withImg}/${FIGURES.length}`);

// ---- questions.ts ----
const qLines = [];
for (const axis of AXIS_IDS) {
  qLines.push(`  ${axis}: [`);
  for (const [text, effect, tier, weight] of QUESTIONS[axis]) {
    qLines.push(`    { text: ${q(text)}, effect: ${effect}, tier: ${tier}, weight: ${weight} },`);
  }
  qLines.push(`  ],`);
}
const qTs =
  `// AUTO-GENERATED by scripts/export-compass-data.mjs — do not edit by hand.\n` +
  `import type { QuestionMap, AlignQuestion } from './types';\n\n` +
  `export const QUESTIONS: QuestionMap = {\n${qLines.join('\n')}\n};\n`;
fs.writeFileSync(path.join(OUT, 'questions.ts'), qTs);

// ---- align.ts ----
const alignTs =
  `// AUTO-GENERATED by scripts/export-compass-data.mjs — do not edit by hand.\n` +
  `import type { AlignQuestion } from './types';\n\n` +
  `export const ALIGN_QUESTIONS: AlignQuestion[] = [\n` +
  ALIGN.map((a) => `  { text: ${q(a[0])}, target: ${q(a[1])}, tier: ${a[2]}, weight: ${a[3]} },`).join('\n') +
  `\n];\n`;
fs.writeFileSync(path.join(OUT, 'align.ts'), alignTs);

// ---- report ----
const numeric = Object.values(QUESTIONS).reduce((s, arr) => s + arr.length, 0);
console.log('Exported:');
console.log(`  axes: ${AXES.length}`);
console.log(`  figures: ${FIGURES.length}`);
console.log(`  numeric questions: ${numeric}`);
console.log(`  align questions: ${ALIGN.length}`);
const perAxis = AXIS_IDS.map((a) => `${a}=${QUESTIONS[a].length}`).join(' ');
console.log(`  per axis: ${perAxis}`);
