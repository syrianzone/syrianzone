#!/usr/bin/env node
/**
 * Generate the House page's bundled roster from the seeder's CSV.
 * Run: node scripts/export-house-members.mjs
 *
 * Source of truth: database/seeders/data/house_members_2026.csv (the Omran
 * snapshot the `HouseMembers2026Seeder` loads into `house_members_2026`).
 * Output: resources/js/Pages/House/members2026.ts
 *
 * The page renders the DB rows and falls back to this array when the table is
 * empty or unreadable, and it fills missing social links from it by name, so
 * the two must be the same dataset:
 * `resources/js/Pages/House/members2026.test.ts` fails when they differ.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, 'database/seeders/data/house_members_2026.csv');
const OUT = path.join(ROOT, 'resources/js/Pages/House/members2026.ts');

/** RFC 4180 rows: quoted fields may hold commas, newlines and doubled quotes. */
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = '';
  let quoted = false;

  for (let i = 0; i < text.length; i += 1) {
    const char = text[i];

    if (quoted) {
      if (char === '"') {
        if (text[i + 1] === '"') {
          field += '"';
          i += 1;
        } else {
          quoted = false;
        }
      } else {
        field += char;
      }
      continue;
    }

    if (char === '"') quoted = true;
    else if (char === ',') {
      row.push(field);
      field = '';
    } else if (char === '\n' || char === '\r') {
      if (char === '\r' && text[i + 1] === '\n') i += 1;
      row.push(field);
      field = '';
      if (row.length > 1 || row[0] !== '') rows.push(row);
      row = [];
    } else {
      field += char;
    }
  }

  if (field !== '' || row.length > 0) {
    row.push(field);
    rows.push(row);
  }

  return rows;
}

const [header, ...rows] = parseCsv(fs.readFileSync(SRC, 'utf8'));
const cell = (row, column) => row[header.indexOf(column)] ?? '';

// The columns the page reads, in the shape `Member2026` declares. `source_url`
// is the same on every row, so it travels once as OMran_SOURCE_URL.
const COLUMNS = [
  'name_ar', 'governorate_ar', 'district', 'town', 'gender', 'birth_year', 'age',
  'selection_method', 'category', 'status', 'member_number', 'management_position',
  'facebook_url', 'twitter_url',
];

const members = rows
  .filter((row) => row.length >= header.length)
  .map((row) => Object.fromEntries(COLUMNS.map((column) => [column, cell(row, column)])));

const sourceUrls = new Set(rows.map((row) => cell(row, 'source_url')).filter(Boolean));
if (sourceUrls.size !== 1) {
  throw new Error(`house_members_2026.csv must carry one source_url, found ${sourceUrls.size}`);
}

const q = (value) => JSON.stringify(value);

const file =
  `// AUTO-GENERATED by scripts/export-house-members.mjs from\n` +
  `// database/seeders/data/house_members_2026.csv (Omran snapshot). Do not hand-edit;\n` +
  `// edit the CSV and re-run the script.\n` +
  `export interface Member2026 {\n` +
  `  name_ar: string; governorate_ar: string; district: string; town: string; gender: string; birth_year: string; age: string; selection_method: string; category: string; status: string; member_number: string; management_position: string; facebook_url?: string | null; twitter_url?: string | null;\n` +
  `}\n` +
  `export const OMran_SOURCE_URL = ${q(encodeURI([...sourceUrls][0]))};\n` +
  `export const MEMBERS_2026: Member2026[] = [${members.map((m) => JSON.stringify(m)).join(', ')}];\n`;

fs.writeFileSync(OUT, file);
console.log(`wrote ${path.relative(ROOT, OUT)}: ${members.length} members`);
